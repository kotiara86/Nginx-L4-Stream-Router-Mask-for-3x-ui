#!/usr/bin/env bash
# ============================================================================
#  RoscomVPN Routing - updater (АДДОН)
#  Проект: Nginx-L4-Stream-Router-Mask-for-3x-ui
#  Назначение: держать клиентские правила маршрутизации в подписках свежими.
#  ВАЖНО: не трогает stream{} и правила L4, работает только с L7-подписками.
# ============================================================================
set -uo pipefail

CONF_FILE=/etc/roscom-routing/roscom-routing.conf
if [ -r "$CONF_FILE" ]; then . "$CONF_FILE"; fi

PROFILE="$ROUTING_PROFILE"
[ -n "$PROFILE" ] || PROFILE=default

UPSTREAM="$ROUTING_UPSTREAM"
[ -n "$UPSTREAM" ] || UPSTREAM=https://raw.githubusercontent.com/hydraponique/roscomvpn-routing/main

STATE_DIR=/var/lib/roscom-routing
WWW_DIR=/var/www/html/routing
SNIPPET=/etc/nginx/snippets/roscom-routing-headers.conf
LOG=/var/log/roscom-routing.log

DRY=0
case " $* " in *" --no-reload "*) DRY=1 ;; esac

log() { echo "$(date '+%F %T') $*" >> "$LOG"; }

mkdir -p "$STATE_DIR" "$WWW_DIR/happ" "$WWW_DIR/incy" "$WWW_DIR/mihomo" /etc/nginx/snippets

case "$PROFILE" in
  default)   HAPP_F=DEFAULT ; IN_F=DEFAULT ;;
  whitelist) HAPP_F=WHITELIST ; IN_F=WHITELIST ;;
  jsonsub)   HAPP_F=JSONSUB ; IN_F=JSONSUB ;;
  off)       HAPP_F= ; IN_F= ;;
  *) log "unknown ROUTING_PROFILE: $PROFILE"; echo "unknown ROUTING_PROFILE: $PROFILE" >&2; exit 2 ;;
esac

fetch() {
  _url="$1"
  _dest="$2"
  if curl -fsS --max-time 25 --retry 2 --retry-delay 3 -A roscom-routing-addon/1.1 -o "$_dest.tmp" "$_url" 2>>"$LOG" && [ -s "$_dest.tmp" ]; then
    mv -f "$_dest.tmp" "$_dest"
    return 0
  fi
  rm -f "$_dest.tmp"
  return 1
}

check_deeplink() {
  python3 - "$1" <<'PY'
import base64, json, sys
raw = open(sys.argv[1], "r", encoding="utf-8").read().strip()
if not raw.startswith("happ://routing/"):
    print("not-a-happ-deeplink"); sys.exit(1)
payload = raw.rsplit("/", 1)[-1]
try:
    data = json.loads(base64.b64decode(payload + "=" * (-len(payload) % 4)).decode("utf-8"))
except Exception as exc:
    print("decode-error: " + str(exc)); sys.exit(1)
if not isinstance(data, dict) or not data.get("Name"):
    print("profile-without-Name"); sys.exit(1)
if len(raw) > 16384:
    print("deeplink-too-long: " + str(len(raw))); sys.exit(1)
print("ok: " + str(data.get("Name")))
PY
}

check_json() {
  python3 - "$1" <<'PY'
import json, sys
try:
    doc = json.load(open(sys.argv[1], "r", encoding="utf-8"))
except Exception as exc:
    print("json-error: " + str(exc)); sys.exit(1)
if not isinstance(doc, dict) or not doc.get("Name"):
    print("profile-without-Name"); sys.exit(1)
print("ok: " + str(doc.get("Name")))
PY
}

FAILED=0

if [ "$PROFILE" != off ]; then
  if fetch "$UPSTREAM/HAPP/$HAPP_F.DEEPLINK" "$STATE_DIR/happ.deeplink" && check_deeplink "$STATE_DIR/happ.deeplink" >>"$LOG" 2>&1; then
    install -m 0644 "$STATE_DIR/happ.deeplink" "$WWW_DIR/happ/$PROFILE.deeplink"
  else
    FAILED=1
    log "warn: happ deeplink не обновлён, оставлен последний рабочий"
  fi

  if fetch "$UPSTREAM/HAPP/$HAPP_F.JSON" "$STATE_DIR/happ.json" && check_json "$STATE_DIR/happ.json" >>"$LOG" 2>&1; then
    install -m 0644 "$STATE_DIR/happ.json" "$WWW_DIR/happ/$PROFILE.json"
  else
    FAILED=1
    log "warn: happ json не обновлён"
  fi

  if fetch "$UPSTREAM/INCY/$IN_F.DEEPLINK" "$STATE_DIR/incy.deeplink"; then
    install -m 0644 "$STATE_DIR/incy.deeplink" "$WWW_DIR/incy/$PROFILE.deeplink"
  else
    log "warn: incy deeplink не обновлён"
  fi

  if fetch "$UPSTREAM/MIHOMO/default.yaml" "$STATE_DIR/mihomo.yaml"; then
    install -m 0644 "$STATE_DIR/mihomo.yaml" "$WWW_DIR/mihomo/default.yaml"
  else
    log "warn: mihomo шаблон не обновлён"
  fi
fi

# ---- генерация include-файла с заголовками для подписок --------------------
DEEPLINK_FILE="$WWW_DIR/happ/$PROFILE.deeplink"
TMP_SNIPPET="$STATE_DIR/headers.new"
PROFILE="$PROFILE" DEEPLINK_FILE="$DEEPLINK_FILE" TMP_SNIPPET="$TMP_SNIPPET" python3 <<'PY'
import datetime, os
profile = os.environ["PROFILE"]
dl_path = os.environ["DEEPLINK_FILE"]
lines = [
    "# RoscomVPN routing headers - generated by roscom-routing-update.sh",
    "# profile: " + profile,
    "# updated: " + datetime.datetime.now().strftime("%F %T"),
    "proxy_hide_header Routing;",
    "proxy_hide_header Routing-Enable;",
]
if profile != "off" and os.path.exists(dl_path):
    dl = open(dl_path, "r", encoding="utf-8").read().strip()
    if dl:
        lines.append('add_header Routing "' + dl + '" always;')
        lines.append('add_header Routing-Enable "true" always;')
open(os.environ["TMP_SNIPPET"], "w", encoding="utf-8").write(chr(10).join(lines) + chr(10))
PY

if ! cmp -s "$TMP_SNIPPET" "$SNIPPET"; then
  if [ -f "$SNIPPET" ]; then cp -f "$SNIPPET" "$STATE_DIR/snippet.prev"; fi
  install -m 0644 "$TMP_SNIPPET" "$SNIPPET"
  if nginx -t >>"$LOG" 2>&1; then
    if [ "$DRY" = 0 ]; then
      systemctl reload nginx >>"$LOG" 2>&1 || log "warn: nginx reload failed"
    fi
    log "заголовки обновлены (profile=$PROFILE), nginx перечитан"
  else
    if [ -f "$STATE_DIR/snippet.prev" ]; then
      cp -f "$STATE_DIR/snippet.prev" "$SNIPPET"
    else
      echo "# roscom routing: placeholder" > "$SNIPPET"
    fi
    FAILED=1
    log "ERROR: nginx -t упал, include-файл откатан"
  fi
fi

echo "{\"profile\": \"$PROFILE\", \"updated\": \"$(date -Is)\", \"failed\": $FAILED, \"upstream\": \"$UPSTREAM\"}" > "$WWW_DIR/meta.json"

PROFILE="$PROFILE" WWW_DIR="$WWW_DIR" python3 <<'PY'
import datetime, os
www = os.environ["WWW_DIR"]
profile = os.environ["PROFILE"]
rows = []
for sub, title in (("happ", "Happ"), ("incy", "INCY")):
    folder = os.path.join(www, sub)
    if not os.path.isdir(folder):
        continue
    for name in sorted(os.listdir(folder)):
        rows.append('<li><a href="' + sub + "/" + name + '">' + title + ": " + name + "</a></li>")
if os.path.exists(os.path.join(www, "mihomo", "default.yaml")):
    rows.append('<li><a href="mihomo/default.yaml">Mihomo: шаблон default.yaml</a></li>')
html = [
    "<!doctype html>",
    '<html lang="ru"><head><meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width,initial-scale=1">',
    "<title>RoscomVPN routing</title>",
    "<style>body{font-family:system-ui,sans-serif;max-width:640px;margin:2rem auto;padding:0 1rem;line-height:1.6;color:#1f1e1d;background:#f5f0e8}a{color:#c96442}</style>",
    "</head><body>",
    "<h1>RoscomVPN routing</h1>",
    "<p>Активный профиль: <b>" + profile + "</b>. Обновлено: " + datetime.datetime.now().strftime("%F %T") + ".</p>",
    "<p>Happ получает профиль автоматически из заголовка подписки. Ссылки ниже - для ручного импорта.</p>",
    "<ul>" + "".join(rows) + "</ul>",
    "</body></html>",
]
open(os.path.join(www, "index.html"), "w", encoding="utf-8").write(chr(10).join(html))
PY

log "готово: profile=$PROFILE failed=$FAILED"
[ "$FAILED" = 0 ]
