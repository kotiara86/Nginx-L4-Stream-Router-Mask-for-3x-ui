#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
clash-merge.py - вклеить правила RoscomVPN в YAML подписки 3x-ui (Clash/Mihomo).

Зачем: Clash и Mihomo не читают заголовок Routing: happ://routing/onadd/...
(это формат Happ). Поэтому правила приходится вставлять в сам YAML подписки.

Что делает:
  * берёт из шаблона RoscomVPN группы, rule-providers, rules и общие
    настройки (dns, tun, sniffer, порты), не меняя их;
  * подставляет прокси из подписки 3x-ui - inline в раздел proxies
    либо ссылкой proxy-providers на URL подписки (режим provider);
  * группы шаблона сохраняются: в rules они упоминаются по именам,
    подменять их группами из подписки нельзя;
  * проверяет, что все группы, на которые ссылаются rules, существуют,
    и что имена прокси не дублируются.

Примеры:
  clash-merge.py --sub https://ynas86.shop/sub/KEY/clash --out merged.yaml
  clash-merge.py --sub ./sub.yaml --template ./default.yaml --check
  clash-merge.py --sub https://ynas86.shop/sub/KEY/clash --mode provider --out merged.yaml

Код возврата: 0 - успех, 1 - проверка не прошла, 2 - ошибка входа.
"""

import argparse
import sys
import urllib.request

UA = "roscom-routing-addon/1.2 clash-merge"
DEFAULT_TEMPLATE = "https://raw.githubusercontent.com/hydraponique/roscomvpn-routing/main/MIHOMO/default.yaml"

KEEP = (
    "mixed-port", "port", "socks-port", "redir-port", "tproxy-port",
    "mode", "log-level", "allow-lan", "bind-address", "ipv6",
    "unified-delay", "tcp-concurrent", "find-process-mode", "profile",
    "dns", "tun", "sniffer", "hosts", "experimental", "geodata-mode",
    "geox-url", "external-controller", "secret", "keep-alive-interval",
)

BUILTIN = ("DIRECT", "REJECT", "REJECT-DROP", "PASS", "COMPATIBLE", "no-resolve")


def read_src(src):
    if src.startswith(("http://", "https://")):
        req = urllib.request.Request(src, headers={"User-Agent": UA})
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.read().decode("utf-8", "replace")
    with open(src, "r", encoding="utf-8") as fh:
        return fh.read()


def is_key_line(line):
    if not line or line[0] in " #-":
        return False
    head, sep, _ = line.partition(":")
    if not sep or not head:
        return False
    return all(ch.isalnum() or ch in "-_" for ch in head.strip())


def sections(text):
    pre, blocks, order, cur = [], {}, [], None
    for line in text.splitlines():
        if is_key_line(line):
            cur = line.split(":", 1)[0].strip()
            order.append(cur)
            blocks[cur] = [line]
        elif cur is None:
            pre.append(line)
        else:
            blocks[cur].append(line)
    return pre, blocks, order


def group_names(block):
    names = []
    for line in block:
        s = line.strip()
        if s.startswith("- name:"):
            names.append(s[len("- name:"):].strip().strip("'\""))
    return names


def proxy_names(block):
    names = []
    for line in block:
        s = line.strip()
        if s.startswith("name:"):
            names.append(s[len("name:"):].strip().strip("'\""))
        elif s.startswith("- {"):
            pass
    return names


def rule_targets(block):
    targets = []
    for line in block:
        s = line.strip()
        if s.startswith("- "):
            s = s[2:]
        parts = [p.strip() for p in s.split(",")]
        if not parts:
            continue
        kind = parts[0]
        if kind in ("MATCH", "FINAL") and len(parts) > 1:
            targets.append(parts[1])
        elif kind in ("RULE-SET", "GEOIP", "IP-CIDR", "IP-CIDR6", "DOMAIN-SUFFIX") and len(parts) > 2:
            targets.append(parts[2])
        elif kind in ("AND", "OR", "NOT") and len(parts) > 2:
            targets.append(parts[-1])
    out = []
    for t in targets:
        if t and t not in out:
            out.append(t)
    return out


def provider_block(url):
    return [
        "proxy-providers:",
        "  sub:",
        "    type: http",
        "    url: " + url,
        "    path: ./provider/proxies.yaml",
        "    interval: 86400",
        "    health-check:",
        "      enable: true",
        "      url: https://www.gstatic.com/generate_204",
        "      interval: 300",
    ]


def merge(sub_text, tpl_text, sub_url=None, mode="proxies", source=""):
    tpl_pre, tpl_sections, tpl_order = sections(tpl_text)
    _sub_pre, sub_sections, _sub_order = sections(sub_text)

    inline = sub_sections.get("proxies")
    providers = sub_sections.get("proxy-providers")

    warn = []
    out = []
    stamp = "# generated by clash-merge.py (roscom-routing addon)" + chr(10)
    if source:
        stamp += "# source: " + source + chr(10)
    stamp += "# профиль маршрутизации RoscomVPN, режим: " + mode + chr(10)
    out.append(stamp.rstrip(chr(10)))

    for line in tpl_pre:
        if line.strip():
            out.append(line)

    if mode == "provider":
        if not sub_url:
            raise ValueError("режим provider требует URL подписки, а не файл")
        out.append(chr(10).join(provider_block(sub_url)))
    elif inline:
        out.append(chr(10).join(inline))
    elif providers:
        out.append(chr(10).join(providers))
        warn.append("в подписке были только proxy-providers, они перенесены как есть")
    else:
        raise ValueError("в подписке нет ни proxies, ни proxy-providers")

    if "proxy-groups" not in tpl_sections:
        raise ValueError("в шаблоне нет proxy-groups")
    out.append(chr(10).join(tpl_sections["proxy-groups"]))

    for key in ("rule-providers", "rules"):
        if key in tpl_sections:
            out.append(chr(10).join(tpl_sections[key]))
        else:
            warn.append("в шаблоне нет раздела " + key)

    for key in tpl_order:
        if key in KEEP and key in tpl_sections:
            out.append(chr(10).join(tpl_sections[key]))

    groups = group_names(tpl_sections.get("proxy-groups", []))
    targets = rule_targets(tpl_sections.get("rules", []))
    missing = [t for t in targets if t not in groups and t not in BUILTIN]
    if missing:
        warn.append("в rules есть группы, которых нет в proxy-groups: " + ", ".join(missing))

    if mode != "provider" and inline:
        names = proxy_names(inline)
        dupes = [n for n in names if names.count(n) > 1]
        if dupes:
            warn.append("дубли имён прокси: " + ", ".join(sorted(set(dupes))))

    return chr(10).join(out).rstrip(chr(10)) + chr(10), warn, {
        "proxies": 0 if mode == "provider" else len(proxy_names(inline or [])),
        "groups": len(groups),
        "rules": len([l for l in tpl_sections.get("rules", []) if l.strip().startswith("- ")]),
    }


def main(argv):
    ap = argparse.ArgumentParser(description="Склеить правила RoscomVPN с YAML подписки 3x-ui")
    ap.add_argument("--sub", required=True, help="URL или файл подписки sub-clash")
    ap.add_argument("--template", default=DEFAULT_TEMPLATE, help="шаблон Mihomo RoscomVPN")
    ap.add_argument("--out", default="-", help="куда писать результат, '-' = stdout")
    ap.add_argument("--mode", choices=("proxies", "provider"), default="proxies",
                    help="proxies: вклеить прокси, provider: сослаться на URL подписки")
    ap.add_argument("--check", action="store_true", help="только проверить, ничего не писать")
    args = ap.parse_args(argv)

    try:
        sub_text = read_src(args.sub)
        tpl_text = read_src(args.template)
        merged, warn, stats = merge(sub_text, tpl_text, args.sub, args.mode, args.sub)
    except Exception as exc:
        print("ERROR: " + str(exc), file=sys.stderr)
        return 2

    for w in warn:
        print("WARN: " + w, file=sys.stderr)
    print("OK: proxies=" + str(stats["proxies"]) + " groups=" + str(stats["groups"])
          + " rules=" + str(stats["rules"]) + " mode=" + args.mode, file=sys.stderr)

    if args.check:
        return 1 if any("нет в proxy-groups" in w for w in warn) else 0

    if args.out == "-":
        sys.stdout.write(merged)
    else:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(merged)
    return 1 if any("нет в proxy-groups" in w for w in warn) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
